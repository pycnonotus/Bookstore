import assert from 'node:assert/strict';
import { cosine, rankEmbeddings } from '../../src/utils/embeddingSearch.js';
import { searchBooks } from '../../src/utils/bookSearch.js';
import books from '../../mock-data/data.json' with { type: 'json' };
assert.equal(cosine([1, 0], [1, 0]), 1);
assert.equal(cosine([1, 0], [0, 1]), 0);
assert.equal(cosine([0, 0], [0, 0]), 0);
assert.throws(() => cosine([1], [1, 2]));
const sample = [{ id: 'math' }, { id: 'art' }];
assert.equal(rankEmbeddings([1, 0], [[1, 0], [0, 1]], sample)[0].book.id, 'math');
assert.throws(() => rankEmbeddings([1], [], sample));
const target = books.find(book => book.topic === 'math');
const semanticOnly = searchBooks('zzzznonexistent', '', [{ id: target.id, score: 0.9 }]);
assert.equal(semanticOnly.books[0].id, target.id);
const expensive = books.find(book => book.name === 'React, Angular, or Vue, Pug!');
assert.ok(!searchBooks('zzzznonexistent under $5', '', [{ id: expensive.id, score: 0.99 }]).books.length);
console.log('Passed: cosine similarity, invalid index checks, semantic-only matches, hard budget constraints.');
