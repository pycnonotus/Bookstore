import assert from 'node:assert/strict';
import books from '../data/books.json' with { type: 'json' };
import { strictBookMatches } from '../utils/strictBookSearch.js';
import { rankEmbeddings } from '../utils/embeddingSearch.js';
const ids = books.slice(0, 6).map(book => book.id);
const matches = [0.899999, 0.9, 0.900001, 0.99, NaN, Infinity].map((score, index) => ({ id: ids[index], score }));
assert.deepEqual(strictBookMatches('', matches).map(row => row.score), [0.99, 0.900001, 0.9]);
assert.equal(strictBookMatches('Forms of Silence', [{id: books[0].id, score:0.89}]).length, 0, 'Exact title cannot bypass cutoff');
assert.equal(strictBookMatches('', []).length, 0);
assert.equal(strictBookMatches('', [{id:'unknown',score:1}]).length, 0);
assert.equal(strictBookMatches('', [{id:ids[0],score:1},{id:ids[0],score:1}]).length, 1);
assert.ok(strictBookMatches('', books.slice(0, 6).map(book => ({id:book.id,score:0.95}))).length > 3, 'Return every qualifying result');
const all = books.map(book => ({id:book.id,score:0.95}));
assert.ok(strictBookMatches('math at least $40', all).every(({book}) => book.topic === 'math' && book.price >= 40));
assert.ok(strictBookMatches('under $0', all).length === 0);
assert.equal(rankEmbeddings([1,0], [[0.89,Math.sqrt(1-0.89**2)],[0.91,Math.sqrt(1-0.91**2)]], books.slice(0,2)).length, 1);
console.log('Passed: raw 0.9 inclusive cutoff, invalid scores, no keyword bypass, all qualifying results, budgets and topics.');
